const {app,BrowserWindow}=require('electron')
const assert=require('node:assert/strict')
const {resolve}=require('node:path')
app.setPath('userData',resolve('tmp/mac-scene-camera/profile'))
const deadline=setTimeout(()=>app.exit(1),45000)
app.whenReady().then(async()=>{
 let win
 try{
  win=new BrowserWindow({show:false,width:1280,height:900,webPreferences:{sandbox:true,contextIsolation:true,nodeIntegration:false,backgroundThrottling:false}})
  win.webContents.on('console-message',event=>{if(event.level==='error')console.error(event.message)})
  const js=source=>win.webContents.executeJavaScript(source)
  const wait=async(expression,message)=>{
   for(let n=0;n<100;n++){if(await js(expression))return;await new Promise(done=>setTimeout(done,25))}
   throw new Error(message+': '+JSON.stringify(await js('({logs:window.logs,messages:window.messages.map(m=>m.name),status:scene.programOutputStatus})')))
  }
  await win.loadFile(resolve('tmp/mac-scene-camera/index.html'))
  await wait('window.tracks?.some(t=>t.readyState==="live")','Synthetic camera should start')
  await js(`(()=>{const preview=document.querySelector('[data-program-scene-preview]');const rect=document.querySelector('[data-program-scene-participant-preview]').getBoundingClientRect();preview.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,cancelable:true,clientX:rect.left+rect.width/2,clientY:rect.top+rect.height/2}))})()`)
  await wait('!!document.querySelector(\'[data-scene-object-action="hide"]\')','Hide menu should open')
  await js(`document.querySelector('[data-scene-object-action="hide"]').click()`)
  await wait('document.querySelector("[data-program-scene-refresh]").dataset.pendingChanges==="true"','Hide should change the draft')
  assert.equal(await js('scene.programScene.enabled'),true)
  await js(`document.querySelector('[data-program-scene-refresh]').click()`)
  await wait('document.querySelector("[data-program-scene-refresh]").dataset.pendingChanges==="false"','Refresh should apply camera removal and clear attention')
  assert.equal(await js('scene.programSnapshot.scene.captureSourceId'),null)
  console.log('PASS: real Scene publication clears attention after Hide → Refresh')
  await wait('window.tracks.every(t=>t.readyState==="ended")','Unused hidden camera should release its tracks')
  console.log('PASS: hidden camera releases all media tracks')
  await js(`scene.setProgramScene({captureSourceId:'camera'})`)
  await wait('window.tracks.some(t=>t.readyState==="live")','Selecting the camera again should reopen it')
  await js(`document.querySelector('[data-program-scene-refresh]').click()`)
  await wait('document.querySelector("[data-program-scene-refresh]").dataset.pendingChanges==="false"','Reopened camera should publish')
  console.log('PASS: selecting a hidden camera again reopens and publishes it')

  await js(`scene.removeCaptureSource('camera')`)
  await wait('document.querySelector("[data-program-scene-refresh]").dataset.pendingChanges==="true"','Removing a source should leave a publishable camera-free draft')
  await js(`document.querySelector('[data-program-scene-refresh]').click()`)
  await wait('document.querySelector("[data-program-scene-refresh]").dataset.pendingChanges==="false"','Refresh after source removal should not stay blinking forever')
  console.log('PASS: removing a source preserves a publishable live Scene')
  for(const owner of ['channels','activeFile','selectedFile','informationMedia']){
   await js(`window.patch({captureSources:[window.cameraEntry]});scene.setProgramScene({captureSourceId:'camera'})`)
   await wait('window.tracks.some(t=>t.readyState==="live")','Camera should restart before owner test')
   await js(`document.querySelector('[data-program-scene-refresh]').click()`)
   await wait('document.querySelector("[data-program-scene-refresh]").dataset.pendingChanges==="false"','Camera should be published before owner test')
   await js(`window.patch(${owner==='channels'?`{channels:{other:{file:window.cameraEntry}}}`:`{${owner}:window.cameraEntry}`});scene.setProgramScene({captureSourceId:null})`)
   await wait('document.querySelector("[data-program-scene-refresh]").dataset.pendingChanges==="true"','Hide should remain a draft until Refresh')
   assert.equal(await js('window.tracks.some(t=>t.readyState==="live")'),true,'Published camera must remain live until Refresh')
   await js(`document.querySelector('[data-program-scene-refresh]').click()`)
   await wait('document.querySelector("[data-program-scene-refresh]").dataset.pendingChanges==="false"','Shared camera removal should publish')
   assert.equal(await js('window.tracks.some(t=>t.readyState==="live")'),true,`${owner} must retain the camera`)
   await js(`window.patch(${owner==='channels'?'{channels:{}}':`{${owner}:null}`})`)
   await wait('window.tracks.every(t=>t.readyState==="ended")',`Removing ${owner} should release the camera`)
  }
  console.log('PASS: channel, active output, selected source and information screen retain their camera until no longer used')
  await js(`scene.setProgramScene({enabled:false,captureSourceId:'camera'})`)
  await wait('window.tracks.some(t=>t.readyState==="live")','Off-air preview should start the camera')
  await js(`scene.setProgramScene({captureSourceId:null})`)
  await wait('window.tracks.every(t=>t.readyState==="ended")','Hiding an off-air preview should release the camera without Refresh')
  console.log('PASS: hiding an off-air camera releases it without publishing a Scene')
  await js('window.unmount()')
  clearTimeout(deadline);win.destroy();app.quit()
 }catch(error){console.error(error);clearTimeout(deadline);if(win&&!win.isDestroyed())win.destroy();app.exit(1)}
})
