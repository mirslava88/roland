const assert = require('node:assert/strict')
const { signatureInfo, sameSigningTeam } = require('./verify-mac-signing.cjs')
const signed = team => `CodeDirectory v=20500 flags=0x10000(runtime)\nSignature size=4806\nTeamIdentifier=${team}\n`
const root = signatureInfo(signed('MC64G6WLAX'), 'PDM.app')
assert.equal(root.team, 'MC64G6WLAX')
assert.throws(() => signatureInfo('CodeDirectory flags=0x10002(adhoc,runtime)\nSignature=adhoc\nTeamIdentifier=not set', 'PDM.app'), /Ad-hoc signing/)
assert.throws(() => signatureInfo(signed('MC64G6WLAX').replace('Signature size=4806', 'Signature=adhoc'), 'PDM.app'), /Team ID/)
assert.throws(() => signatureInfo(signed('MC64G6WLAX').replace('0x10000(runtime)', '0x0(none)'), 'PDM.app'), /Hardened runtime/)
assert.throws(() => sameSigningTeam(root, signatureInfo(signed('OTHERTEAM1'), 'Electron Framework'), 'Electron Framework'), /Team ID differs/)
sameSigningTeam(root, signatureInfo(signed('MC64G6WLAX'), 'Electron Framework'), 'Electron Framework')
const { builderConfig } = require('../build/editions.cjs')
assert.ok(builderConfig('standard', 'darwin').afterSign.endsWith('afterSign-mac.cjs'))
assert.ok(builderConfig('stream', 'darwin').afterSign.endsWith('afterSign-mac.cjs'))
assert.equal(builderConfig('standard', 'win32').afterSign, undefined)
console.log('PASS: ad-hoc, missing Team ID, mixed signing teams and disabled hardened runtime are rejected before creating a release DMG; Windows unchanged')
