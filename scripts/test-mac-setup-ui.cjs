const { app, BrowserWindow } = require('electron')
const assert = require('node:assert/strict')
const { resolve } = require('node:path')
const { writeFileSync } = require('node:fs')
app.setPath('userData', resolve('tmp/mac-setup-ui/profile'))
const deadline = setTimeout(() => app.exit(1), 45000)
app.whenReady().then(async () => {
  let win
  try {
    win = new BrowserWindow({ show: false, width: 1280, height: 800, useContentSize: true,
      webPreferences: { sandbox: true, contextIsolation: true, nodeIntegration: false, backgroundThrottling: false } })
    const js = source => win.webContents.executeJavaScript(source)
    const pause = ms => new Promise(done => setTimeout(done, ms))
    const wait = async (expression, message) => {
      for (let i = 0; i < 100; i++) { if (await js(expression)) return; await pause(25) }
      throw Error(message)
    }
    const load = async query => { await win.loadFile(resolve('tmp/mac-setup-ui/index.html'), { search: query }); await pause(150) }
    await load('windows&screen&accessibility')
    assert.equal(await js('!!document.querySelector("[data-mac-setup-dialog]")'), false)
    assert.equal(await js('fixture.reads'), 0)
    await load('ready')
    assert.equal(await js('!!document.querySelector("[data-mac-setup-dialog]")'), false)
    assert.deepEqual(await js('fixture.opened'), [])
    console.log('PASS: Windows and already configured Mac have no startup guide or settings jump')

    await load('accessibility')
    await wait('fixture.opened.length===1', 'Missing Accessibility should open its settings on startup')
    assert.deepEqual(await js('fixture.opened'), ['accessibility'])
    assert.equal(await js('document.querySelector(".mac-setup-workspace").inert'), true)
    await js('document.querySelector("[data-mac-show-application]").click()')
    assert.equal(await js('fixture.reveals'), 1)
    await js('fixture.accessibility=true;window.dispatchEvent(new Event("focus"))')
    await wait('document.querySelector("[data-mac-permission=accessibility]").dataset.granted==="true"', 'Returning from settings should notice granted access')
    await js('document.querySelector("[data-mac-restart]").click()')
    assert.equal(await js('fixture.restarts'), 1)
    await js('document.querySelector("[data-mac-continue]").click()')
    await wait('!document.querySelector("[data-mac-setup-dialog]")', 'Continue should restore workspace interaction')
    assert.equal(await js('document.querySelector(".mac-setup-workspace").inert'), false)
    console.log('PASS: exact missing permission opens, app reveal works, focus rechecks access and restart/continue are available')

    await load('screen&accessibility&keynote')
    await wait('fixture.opened.length===1', 'Screen Recording must be the first missing permission')
    assert.deepEqual(await js('fixture.opened'), ['screen'])
    await js('window.selectPptx()')
    await wait('!!document.querySelector("[data-mac-keynote-required]")', 'Selecting PPTX without Keynote should display installation instructions')
    assert.equal(await js('document.body.innerText.includes("Presentation Display Manager Stream")'), true)
    assert.equal(await js('document.body.innerText.includes("Microsoft PowerPoint")'), true)
    await js('document.querySelector("[data-mac-keynote-required] button").click()')
    assert.equal(await js('fixture.downloads'), 1)
    for (const [width, height] of [[1280, 800], [1000, 720], [880, 720]]) {
      win.setContentSize(width, height); await pause(80)
      const fits = await js(`(()=>{const d=document.querySelector('[data-mac-setup-dialog]'),r=d.getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight&&r.left>=0&&r.right<=innerWidth&&d.scrollHeight<=d.clientHeight})()`)
      assert.equal(fits, true, `Guide must fit without scrollbars at ${width}×${height}`)
    }
    writeFileSync(resolve('tmp/mac-setup-ui/missing-requirements.png'), (await win.webContents.capturePage()).toPNG())
    await js('document.querySelector("[data-mac-open-privacy=accessibility]").click()')
    assert.deepEqual(await js('fixture.opened'), ['screen', 'accessibility'])
    await js('fixture.screen="granted";fixture.accessibility=true;fixture.installed=true;document.querySelector("[data-mac-recheck]").click()')
    await wait('document.querySelector("[data-mac-continue]")?.textContent==="Продолжить"', 'Manual recheck should detect installation and both permissions')
    await js('document.querySelector("[data-mac-continue]").click()')
    await wait('!document.querySelector("[data-mac-setup-dialog]")', 'Ready guide should close')
    await js('fixture.installed=false')
    assert.equal(await js('window.tryPptx()'), false, 'PPTX must be rejected before TAKE with missing Keynote')
    await wait('!!document.querySelector("[data-mac-keynote-required]")', 'PPTX retry should reopen setup')
    assert.deepEqual(await js('fixture.opened'), ['screen', 'accessibility'], 'Retries must not endlessly steal focus to settings')
    assert.deepEqual(await js('fixture.errors'), [])
    console.log('PASS: PPTX missing Keynote, both missing permissions, App Store, edition name, compact layout, successful recheck and retry without focus loop')
    await load('intro&screen&accessibility')
    await wait('!!document.querySelector("[data-mac-setup-dialog]")', 'Mac setup should appear before first-run introduction')
    await js('window.dispatchEvent(new KeyboardEvent("keydown",{key:"Tab",bubbles:true}))')
    assert.equal(await js('document.querySelector("[data-mac-setup-dialog]").contains(document.activeElement)'), true)
    await js('window.dispatchEvent(new KeyboardEvent("keydown",{key:"Escape",bubbles:true}))')
    await wait('!document.querySelector("[data-mac-setup-dialog]")', 'Escape must close setup, not introduction underneath')
    assert.equal(await js('!!document.querySelector("[data-pdm-onboarding]")'), true)
    console.log('PASS: first-run introduction does not intercept keyboard focus or Escape from Mac setup')
    await js('window.unmount()')
    clearTimeout(deadline); win.destroy(); app.quit()
  } catch (error) {
    console.error(error); clearTimeout(deadline)
    if (win && !win.isDestroyed()) win.destroy()
    app.exit(1)
  }
})
